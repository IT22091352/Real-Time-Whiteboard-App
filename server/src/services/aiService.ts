    const userPromptText = `User Request: "${userQuestion}"
${(payload.objects || []).length > 0 ? `Existing Board Objects Count: ${payload.objects.length}` : ''}`;

    const parts: any[] = [{ text: `${systemPrompt}\n\n${userPromptText}` }];

    if (payload.image) {
      const base64Data = payload.image.replace(/^data:image\/(png|jpeg|jpg|webp);base64,/, '');
      parts.push({
        inlineData: {
          mimeType: 'image/png',
          data: base64Data,
        },
      });
    }

    const candidateModels = Array.from(
      new Set([this.modelName, 'gemini-2.5-flash', 'gemini-flash-latest', 'gemini-3.5-flash'])
    );
