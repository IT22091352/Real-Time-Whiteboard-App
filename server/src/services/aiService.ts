  /**
   * Deterministic layout sanitizer and bounds validator layer
   */
  public sanitizeAndAdjustLayout(data: AIGenerateWhiteboardResponse): AIGenerateWhiteboardResponse {
    const rawObjects = data.objects || [];
    const MAX_AI_OBJECTS = 100;
    const MAX_TEXT_LENGTH = 500;
    const MAX_POLYGON_POINTS = 50;

    const sanitizedObjects: any[] = [];
    const seenIds = new Set<string>();

    for (let i = 0; i < Math.min(rawObjects.length, MAX_AI_OBJECTS); i++) {
      const obj = rawObjects[i];
      let id = obj.id || `obj-${i + 1}`;
      if (seenIds.has(id)) {
        id = `${id}-${i + 1}`;
      }
      seenIds.add(id);

      // Clamp text length
      let text = obj.text;
      if (text && text.length > MAX_TEXT_LENGTH) {
        text = text.substring(0, MAX_TEXT_LENGTH);
      }

      // Clamp polygon points
      let points = obj.points;
      if (points && points.length > MAX_POLYGON_POINTS) {
        points = points.slice(0, MAX_POLYGON_POINTS);
      }

      // Coordinate normalization safety
      let x = typeof obj.x === 'number' ? obj.x : 0.1 + (i % 5) * 0.18;
      let y = typeof obj.y === 'number' ? obj.y : 0.15 + Math.floor(i / 5) * 0.18;
      let width = typeof obj.width === 'number' ? obj.width : 0.15;
      let height = typeof obj.height === 'number' ? obj.height : 0.08;

      // Keep within bounds [0.02, 0.95]
      x = Math.max(0.02, Math.min(0.95, x));
      y = Math.max(0.02, Math.min(0.95, y));
      width = Math.max(0.02, Math.min(0.8, width));
      height = Math.max(0.02, Math.min(0.8, height));

      // Color mapping
      const color = obj.color || obj.strokeColor || '#000000';
      const fillColor = obj.fillColor || (['sticky'].includes(obj.type) ? '#FEF08A' : '#FFFFFF');
      const size = obj.size || obj.strokeWidth || 2;
      const fontSize = obj.fontSize || 14;

      sanitizedObjects.push({
        ...obj,
        id,
        x,
        y,
        width,
        height,
        color,
        fillColor,
        size,
        fontSize,
        text,
        points,
      });
    }

    // Verify connector reference validity
    const validIds = new Set(sanitizedObjects.map((o) => o.id));
    for (const obj of sanitizedObjects) {
      if (obj.fromId && !validIds.has(obj.fromId)) {
        obj.fromId = undefined;
      }
      if (obj.toId && !validIds.has(obj.toId)) {
        obj.toId = undefined;
      }
    }

    return {
      title: data.title || 'AI Generated Whiteboard',
      description: data.description || 'Structured whiteboard objects generated by AI.',
      objects: sanitizedObjects,
    };
  }

